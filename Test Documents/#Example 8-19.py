#Example 8-19 利用牛顿迭代法求平方根
x=float(input('输入一个实数：'))
y=x/2
n=0
while abs(y*y-x)>1e-8:
    y=(y+x/y)/2
    n=n+1
    print(n,y)
print('%f 的平方根为%f'%(x,y))
